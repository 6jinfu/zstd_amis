const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const values=new Map(),context=vm.createContext({window:{},localStorage:{getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)}});
for(const file of ['standard-seeds.js','standards-data.js','assessment-data.js'])vm.runInContext(fs.readFileSync('app/'+file,'utf8'),context);
const {Standards:S,AssessmentDrafts:A}=context.window,plain=value=>JSON.parse(JSON.stringify(value));
context.Standards=S;
const standard=S.read().standards.find(s=>s.id==='std-collaboration'),abilities=standard.content.cap.map(c=>c[0]);
assert.deepEqual(plain(A.resolve(standard).people.map(p=>p.name)),['张明','李华']);
const questions=A.generate(abilities,{single:2,multi:0,score:1,essay:1},'跨部门项目交付');
assert.equal(questions.length,8);assert.equal(new Set(questions.map(q=>q.id)).size,8);
assert.ok(questions.every(q=>abilities.includes(q.ability)&&q.text.includes('跨部门项目交付')));
assert.equal(questions.filter(q=>q.type==='multi').length,0);assert.ok(questions.filter(q=>q.type==='single').every(q=>q.options.length>=2));
const all=A.generate(abilities,A.defaults(),'团队协作');assert.equal(all.length,12);assert.equal(new Set(all.map(q=>q.type)).size,4);
assert.equal(A.generate(abilities,{single:0,multi:0,score:0,essay:0}).length,0);
const escape=text=>String(text).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const legacy={id:'legacy',ability:abilities[0],text:'保留旧题'};
assert.ok(A.questionMarkup(legacy,0,escape,true).includes('无法判断'));
assert.ok(!A.questionMarkup(all[0],0,escape).includes('<input'));
assert.ok(A.questionMarkup(all[0],0,escape,true).includes('type="radio"'));
const unsafe={id:'unsafe',type:'single',text:'<img src=x>',options:['<script>','安全选项']};
assert.ok(!A.questionMarkup(unsafe,0,escape).includes('<script>'));
const draft={id:'draft',scope:A.resolve(standard).label,questions:all,turns:[{role:'user',text:'团队协作'}]};A.write([draft]);assert.deepEqual(plain(A.read()),plain([draft]));
console.log('PASS scope, capability-only questions, mixed types, zero counts, legacy score, read-only/full preview, escaping, draft round-trip');
const full=A.generate(abilities,{single:5,multi:5,score:5,essay:5});
assert.equal(full.length,40);assert.equal(new Set(full.map(q=>q.text)).size,40);
console.log('PASS maximum counts generate distinct question prompts');
