def clock(value):
    return f'{value // 60:02d}:{value % 60:02d}'

def srt_clock(ms):
    hour, ms = divmod(ms, 3600000)
    minute, ms = divmod(ms, 60000)
    second, ms = divmod(ms, 1000)
    return f'{hour:02d}:{minute:02d}:{second:02d},{ms:03d}'

def voice_text(cues):
    return ''.join(cues).replace('|', '').replace('360', '三百六十度')

def spoken_units(text):
    return len(re.findall(r'[\u4e00-\u9fffA-Za-z0-9]', text.replace('360', '三百六十度')))

def normalized(text):
    return ''.join(re.findall(r'[\u4e00-\u9fffA-Za-z0-9]', text.replace('360', '三百六十度')))

captions = []
for segment in segments:
    cues = segment['cues']
    if not cues:
        continue
    total_ms = (segment['end'] - segment['start']) * 1000
    minimum_ms = 2300
    weights = [spoken_units(cue) for cue in cues]
    spare = total_ms - minimum_ms * len(cues)
    assert spare >= 0
    elapsed_weight = 0
    previous_ms = segment['start'] * 1000
    for i, cue in enumerate(cues):
        elapsed_weight += weights[i]
        end_ms = segment['start'] * 1000 + minimum_ms * (i + 1) + round(spare * elapsed_weight / sum(weights))
        captions.append(dict(index=len(captions)+1, start=previous_ms, end=end_ms, text=cue.replace('|', '\n'), segment=segment['name']))
        previous_ms = end_ms

srt = '\n\n'.join(f"{c['index']}\n{srt_clock(c['start'])} --> {srt_clock(c['end'])}\n{c['text']}" for c in captions) + '\n'
(ROOT / '人才发展_5分钟宣传版_预排字幕.srt').write_text(srt, encoding='utf-8-sig')
