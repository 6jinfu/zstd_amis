from pathlib import Path
from html import escape
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
parts = []
markdown = []


def heading(level, text):
    parts.append(f'<h{level}>{escape(text)}</h{level}>')
    markdown.append('#' * (level + 1) + ' ' + text + '\n')


def paragraph(text):
    parts.append(f'<p>{escape(text)}</p>')
    markdown.append(text + '\n')


def bullets(items):
    parts.append('<ul>' + ''.join('<li>' + escape(text) + '</li>' for text in items) + '</ul>')
    markdown.append('\n'.join('- ' + text for text in items) + '\n')


def table(headers, rows):
    parts.append('<table><thead><tr>' + ''.join('<th><p>' + escape(v) + '</p></th>' for v in headers) + '</tr></thead><tbody>' + ''.join('<tr>' + ''.join('<td><p>' + escape(str(v)) + '</p></td>' for v in row) + '</tr>' for row in rows) + '</tbody></table>')
    markdown.append('| ' + ' | '.join(headers) + ' |\n| ' + ' | '.join('---' for _ in headers) + ' |\n' + '\n'.join('| ' + ' | '.join(str(v).replace('|', '\\|') for v in row) + ' |' for row in rows) + '\n')


def image(name, caption):
    path = 'deliverables/1127-update-20261116/screenshots/' + name + '.jpg'
    if not (ROOT / path).is_file():
        raise FileNotFoundError(path)
    parts.append(f'<img path="@./{path}" caption="{escape(caption, quote=True)}"/>')
    markdown.append(f'![{caption}](screenshots/{name}.jpg)\n')


def append_fragment(name):
    path = ROOT / 'deliverables/1127-ai-workflow-20261116' / name
    for node in ET.fromstring('<root>' + path.read_text() + '</root>'):
        if node.tag.startswith('h'):
            heading(int(node.tag[1:]), ''.join(node.itertext()))
        elif node.tag == 'p':
            paragraph(''.join(node.itertext()))
        elif node.tag == 'table':
            headers = [''.join(cell.itertext()) for cell in node.findall('thead/tr/th')]
            rows = [[''.join(cell.itertext()) for cell in row] for row in node.findall('tbody/tr')]
            table(headers, rows)


